def production(**kwargs):
    values = dict(app_env="production", database_url="postgresql://user:placeholder@db.example/db?sslmode=verify-full",
                  cors_origins=["https://app.example.com"], trusted_hosts=["api.example.com"],
                  frontend_origin="https://app.example.com",
                  google_redirect_uri="https://app.example.com/api/auth/google/callback")
    values.update(kwargs)
    return Settings(_env_file=None, **values)


def test_production_restricts_configuration():
    assert production().app_env == "production"
    for changes in [dict(database_url=None), dict(database_url="postgresql://localhost/db"),
                    dict(cors_origins=["http://app.example.com"]), dict(cors_origins=[]),
                    dict(trusted_hosts=["*"]), dict(trusted_hosts=["localhost"])]:
        with pytest.raises(ValidationError):
            production(**changes)


def test_production_disables_api_docs():
    from app.main import create_app
    app = create_app(production())
    assert app.docs_url is None and app.openapi_url is None


def test_engine_is_lazy_bounded_and_hides_sql_parameters(monkeypatch):
    captured = MagicMock()
    monkeypatch.setattr("app.db.create_engine", captured)
    settings = Settings(_env_file=None, database_url="postgresql://user:secret@localhost/dev")
    build_engine(settings)
    options = captured.call_args.kwargs
    assert options["pool_pre_ping"] and options["hide_parameters"]
    assert options["pool_size"] == 5 and options["max_overflow"] == 5
    assert options["connect_args"]["connect_timeout"] == 3
    assert "statement_timeout=5000" in options["connect_args"]["options"]


@pytest.mark.parametrize(("safe_role", "revision", "expected"), [
    (True, [SCHEMA_REVISION], True), (False, [SCHEMA_REVISION], False),
    (True, [], False), (True, ["0001_foundation"], False),
])
def test_readiness_checks_runtime_role_and_exact_revision(safe_role, revision, expected):
    engine = MagicMock()
    connection = engine.connect.return_value.__enter__.return_value
    role = MagicMock()
    role.scalar_one.return_value = safe_role
    version = MagicMock()
    version.scalars.return_value.all.return_value = revision
    connection.execute.side_effect = [MagicMock(), role, version]
    assert database_ready(engine) is expected
    assert database_ready(None) is False


def test_tenant_context_is_transaction_local_and_parameterized(monkeypatch):
    session = MagicMock()
    session.begin.return_value = nullcontext()
    session_factory = MagicMock()
    session_factory.return_value.__enter__.return_value = session
    monkeypatch.setattr("app.db.Session", session_factory)
    user_id = uuid4()
    with user_session(MagicMock(), user_id) as result:
        assert result is session
    statement, parameters = session.execute.call_args.args
    assert "set_config('app.user_id', :user_id, true)" in str(statement)
    assert parameters == {"user_id": str(user_id)}
    with pytest.raises(ValueError):
        with user_session(MagicMock(), "untrusted-browser-user-id"):
            pass
